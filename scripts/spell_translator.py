def main():
    spell_file = Path('public/rules/spells.json')
    
    with open(spell_file, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    spells = data.get('spells', [])
    manual = manual_translations()
    
    translated_count = 0
    missing = []
    
    for spell in spells:
        en_text = spell.get('atHigherLevelsEn')
        cn_text = spell.get('atHigherLevels')
        
        if en_text and not cn_text:
            spell_name_en = spell.get('nameEn', '')
            
            # Try manual translation
            if spell_name_en in manual:
                spell['atHigherLevels'] = manual[spell_name_en]
                translated_count += 1
            else:
                missing.append({
                    'name': spell.get('name'),
                    'nameEn': spell_name_en,
                    'text': en_text
                })
    
    print(f"手动翻译: {translated_count} 个")
    
    if missing:
        print(f"\n仍有 {len(missing)} 个未翻译:")
        for m in missing:
            print(f"  - {m['name']} ({m['nameEn']})")
    
    # Save the updated data
    with open(spell_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"\n已保存到 {spell_file}")


if __name__ == '__main__':
    main()
